// Bundles the MCP App (src/ui/app.ts + ext-apps) into a single self-contained
// HTML document and writes it as a TypeScript module so the Worker can serve
// it as a ui:// resource without any asset pipeline.
import { build } from "esbuild";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");

const result = await build({
  entryPoints: [path.join(root, "src/ui/app.ts")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: true,
  write: false,
  logLevel: "warning"
});

const script = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
const shell = readFileSync(path.join(root, "src/ui/shell.html"), "utf8");
if (!shell.includes("<!--APP_SCRIPT-->")) {
  throw new Error("src/ui/shell.html is missing the <!--APP_SCRIPT--> marker");
}
const html = shell.replace("<!--APP_SCRIPT-->", () => `<script>\n${script}\n</script>`);

const outDir = path.join(root, "src/ui");
mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, "app-html.generated.ts");
writeFileSync(
  outPath,
  `// Generated by scripts/build-ui.mjs — do not edit.\nexport const WZRDMAIL_APP_HTML: string = ${JSON.stringify(html)};\n`
);
console.log(`wrote ${path.relative(root, outPath)} (${html.length} bytes)`);
